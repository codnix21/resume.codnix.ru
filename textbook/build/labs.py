"""Глава 3. Лабораторные и дополнительные практические работы."""


def _lead(book, title, text):
    paragraph = book._p("", first=0, after=6, align="left")
    book.add_runs(paragraph, title + ". ", bold=True)
    book.add_runs(paragraph, text)


def _paras(book, paragraphs):
    for text in paragraphs:
        book.para(text)


def work(book, number, kind, title, goal, skills, theory, equipment, data, steps, tasks, questions, expected, acceptance, report, mistakes, extra, listing=None):
    book.h(2, f"{kind} {number}. {title}")
    book.para(
        "Продолжительность: время определяет преподаватель. В рабочей программе 2022 года одноимённые занятия длятся один или два академических часа и могут повторяться. "
        "Складывать эти часы в норматив данной работы нельзя: точного однозначного соответствия номера занятия и этой работы в программе нет."
    )
    _lead(book, "Цель", goal)
    _lead(book, "Формируемые навыки и связь с результатами", skills)
    book.para("Теоретическая справка.")
    _paras(book, theory)
    if listing:
        relative, caption = listing
        book.code_file(relative, caption)
    _lead(book, "Оборудование, программное обеспечение и подготовка окружения", equipment)
    _lead(book, "Исходные данные", data)
    book.para("Пошаговый алгоритм.")
    book.numbers(steps)
    book.para("Практические задания. Базовый уровень обязателен. Средний уровень обязателен для оценки выше минимальной. Повышенный уровень выполняется по указанию преподавателя или по желанию студента.")
    book.numbers(tasks)
    book.para("Контрольные вопросы.")
    book.numbers(questions)
    _lead(book, "Ожидаемые результаты", expected)
    book.table(["Признак приёмки", "Как проверить", "Балл"], acceptance, f"Критерии приёмки работы {number}")
    book.para("Сумма по этой таблице — от 0 до 10. Перевод в отметку приведён в главе 5 и применяется только после согласования с локальным положением техникума.")
    _lead(book, "Форма отчёта", report)
    _lead(book, "Типичные ошибки", mistakes)
    _lead(book, "Дополнительное задание повышенной сложности", extra)


